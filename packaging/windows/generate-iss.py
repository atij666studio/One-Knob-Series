"""Generate ONE-KNOB-Series.iss (combined Windows installer) from packaging/plugins.txt.

Run after adding or removing a plug-in:  python packaging/windows/generate-iss.py
"""
import pathlib

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parent.parent
APP_ID = "8E0E4B0B-5D7C-4D2F-9C64-1B8C2F0E7A31"   # keep stable so upgrades replace older installs

plugins = [l.split("|", 1) for l in (ROOT / "packaging" / "plugins.txt").read_text(encoding="utf-8").splitlines()
           if l and not l.startswith("#")]

HEADER = r"""; ============================================================================
;  ONE KNOB Series -- combined Windows installer (Inno Setup 6)
;  Tick the plug-ins and formats you want; everything is ticked by default.
;  GENERATED by packaging/windows/generate-iss.py from packaging/plugins.txt.
;  Build (after packaging/build-all.ps1):
;    ISCC.exe /DAppVersion=1.0.0 /DRootDir=<repo> /DStageDir=<repo>\dist\stage /DOutDir=<repo>\dist\release ONE-KNOB-Series.iss
; ============================================================================

#ifndef AppVersion
  #define AppVersion "1.0.0"
#endif
#ifndef StageDir
  #define StageDir "..\..\dist\stage"
#endif
#ifndef OutDir
  #define OutDir "..\..\dist\release"
#endif
#ifndef RootDir
  #define RootDir "..\.."
#endif
#define AppName      "ONE KNOB Series"
#define AppPublisher "ATIJ STUDIO"
#define AppURL       "https://atij666studio.github.io/atijstudio/plugins/one-knob-series/"

[Setup]
AppId={{@APPID@}
AppName={#AppName}
AppVersion={#AppVersion}
AppVerName={#AppName} {#AppVersion}
AppPublisher={#AppPublisher}
AppPublisherURL={#AppURL}
AppSupportURL={#AppURL}
VersionInfoVersion={#AppVersion}
VersionInfoCompany={#AppPublisher}
VersionInfoProductName={#AppName}
DefaultDirName={autopf}\{#AppPublisher}\{#AppName}
DisableDirPage=yes
DisableProgramGroupPage=yes
PrivilegesRequired=admin
ArchitecturesInstallIn64BitMode=x64compatible
ArchitecturesAllowed=x64compatible
OutputDir={#OutDir}
OutputBaseFilename=ONE-KNOB-Series-v{#AppVersion}-Windows-x64-Setup
Compression=lzma2/ultra64
SolidCompression=yes
WizardStyle=modern
WizardSizePercent=120
LicenseFile={#RootDir}\LICENSE
UninstallDisplayName={#AppName} {#AppVersion}
CloseApplications=yes

[Languages]
Name: "english"; MessagesFile: "compiler:Default.isl"

[Messages]
SelectComponentsDesc=Which plug-ins do you want to install?
SelectComponentsLabel2=Tick the plug-ins you want and untick the ones you want to skip. You can run this installer again later to add more.
SelectTasksDesc=Which plug-in formats do you want?
SelectTasksLabel2=Tick the formats your DAW uses. Most DAWs use VST3; Bitwig and Reaper also support CLAP; Ardour and Carla use LV2.

[Types]
Name: "full";   Description: "All @COUNT@ plug-ins"
Name: "custom"; Description: "Choose plug-ins"; Flags: iscustom

[Components]
"""

TASKS = r"""
[Tasks]
Name: "vst3"; Description: "VST3  (C:\Program Files\Common Files\VST3)"
Name: "clap"; Description: "CLAP  (C:\Program Files\Common Files\CLAP)"
Name: "lv2";  Description: "LV2   (C:\Program Files\Common Files\LV2)"

[Files]
Source: "{#RootDir}\docs\ONE-KNOB-Series-Manual.pdf"; DestDir: "{app}"; Flags: ignoreversion
"""

FILES = r"""; ---- @P@
Source: "{#StageDir}\@P@\VST3\@P@.vst3\*"; DestDir: "{commoncf64}\VST3\@P@.vst3"; Flags: ignoreversion recursesubdirs createallsubdirs; Components: @C@; Tasks: vst3
Source: "{#StageDir}\@P@\CLAP\@P@.clap"; DestDir: "{commoncf64}\CLAP"; Flags: ignoreversion; Components: @C@; Tasks: clap
Source: "{#StageDir}\@P@\LV2\@P@.lv2\*"; DestDir: "{commoncf64}\LV2\@P@.lv2"; Flags: ignoreversion recursesubdirs createallsubdirs; Components: @C@; Tasks: lv2
Source: "{#StageDir}\@P@\@P@-Manual.pdf"; DestDir: "{app}\Manuals"; Flags: ignoreversion; Components: @C@
"""

FOOTER = r"""
[Icons]
Name: "{autoprograms}\{#AppPublisher}\ONE KNOB Series Manual"; Filename: "{app}\ONE-KNOB-Series-Manual.pdf"
Name: "{autoprograms}\{#AppPublisher}\Uninstall ONE KNOB Series"; Filename: "{uninstallexe}"

[Code]
function NextButtonClick(CurPageID: Integer): Boolean;
begin
  Result := True;
  if (CurPageID = wpSelectTasks) and not (WizardIsTaskSelected('vst3') or WizardIsTaskSelected('clap') or WizardIsTaskSelected('lv2')) then
  begin
    MsgBox('Please tick at least one plug-in format.', mbError, MB_OK);
    Result := False;
  end;
end;

procedure CurStepChanged(CurStep: TSetupStep);
begin
  if CurStep = ssDone then
    MsgBox('ONE KNOB Series is installed.' + #13#10 + #13#10 +
           'Rescan plug-ins in your DAW so the new plug-ins appear.' + #13#10 +
           'The manuals are in the Start menu under ATIJ STUDIO.', mbInformation, MB_OK);
end;
"""

out = [HEADER.replace("@APPID@", APP_ID).replace("@COUNT@", str(len(plugins)))]
for name, desc in plugins:
    out.append(f'Name: "{name.lower()}"; Description: "AtiNAMatiC-{name}  —  {desc}"; Types: full custom\n')
out.append(TASKS)
for name, _ in plugins:
    out.append(FILES.replace("@P@", f"AtiNAMatiC-{name}").replace("@C@", name.lower()))
out.append(FOOTER)

target = HERE / "ONE-KNOB-Series.iss"
target.write_text("".join(out), encoding="utf-8-sig", newline="\r\n")
print(f"wrote {target.name}: {len(plugins)} plug-ins")
